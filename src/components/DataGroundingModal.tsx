import React, { useState, useEffect } from 'react';
import {
  ShieldCheck,
  X,
  AlertTriangle,
  CheckCircle2,
  FileText,
  RefreshCw,
  Copy,
  Check,
  Calculator,
  Search,
  Info,
  ShieldAlert,
  ArrowRight,
  ExternalLink,
} from 'lucide-react';
import { FullDiligenceReport, GroundingEvaluationReport, GroundingItemType } from '../types';
import { evaluateReportGrounding } from '../utils/groundingEvaluator';
import { useAuth } from '../context/AuthContext';

interface DataGroundingModalProps {
  isOpen: boolean;
  onClose: () => void;
  report: FullDiligenceReport;
  rawPitchText?: string;
  companyName: string;
}

type FilterMode = 'ALL' | 'PURE_SYNTHESIS_ALERT' | 'MATHEMATICAL_CALCULATION' | 'DIRECT_PITCH_SOURCE';

export const DataGroundingModal: React.FC<DataGroundingModalProps> = ({
  isOpen,
  onClose,
  report,
  rawPitchText,
  companyName,
}) => {
  const { currentUser } = useAuth();
  const [evaluation, setEvaluation] = useState<GroundingEvaluationReport | null>(null);
  const [activeFilter, setActiveFilter] = useState<FilterMode>('ALL');
  const [searchQuery, setSearchQuery] = useState('');
  const [isLiveVerifying, setIsLiveVerifying] = useState(false);
  const [copied, setCopied] = useState(false);
  const [showRawPitch, setShowRawPitch] = useState(false);

  // Compute grounding on open or when report changes
  useEffect(() => {
    if (isOpen && report) {
      const initialEval = evaluateReportGrounding(rawPitchText, report);
      setEvaluation(initialEval);
      if (initialEval.purelySynthesizedCount > 0) {
        setActiveFilter('ALL');
      }
    }
  }, [isOpen, report, rawPitchText]);

  if (!isOpen || !evaluation) return null;

  // Live Deep AI Verification via server endpoint
  const handleRunLiveAIVerification = async () => {
    setIsLiveVerifying(true);
    try {
      let idToken = '';
      if (currentUser) {
        idToken = await currentUser.getIdToken();
      }

      const res = await fetch('/api/grounding-audit', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          ...(idToken ? { Authorization: `Bearer ${idToken}` } : {}),
        },
        body: JSON.stringify({
          pitchText: rawPitchText || '',
          report,
        }),
      });

      if (res.ok) {
        const data = await res.json();
        if (data.success && data.report) {
          setEvaluation({
            ...data.report,
            evaluationMethod: 'AI_DEEP_EVALUATION',
          });
        }
      }
    } catch (e) {
      console.warn('Live AI verification error:', e);
    } finally {
      setIsLiveVerifying(false);
    }
  };

  const handleCopyReport = () => {
    const text = `# PITCH BLACK DATA GROUNDING & SYNTHESIS AUDIT
Target Startup: ${companyName}
Evaluated At: ${new Date(evaluation.evaluatedAt).toLocaleString()}
Score: ${evaluation.score} / 10.0 (Grade ${evaluation.grade})
Evaluation Method: ${evaluation.evaluationMethod}

## EXECUTIVE SUMMARY
${evaluation.evaluationSummary}

## PURELY SYNTHESIZED DATA OUT OF NOWHERE (${evaluation.purelySynthesizedCount} ITEMS)
${
  evaluation.purelySynthesizedItems.length > 0
    ? evaluation.purelySynthesizedItems
        .map(
          (s) =>
            `[${s.severity}] ${s.item} (${s.pillar})\n  Claim in Report: "${s.claimInReport}"\n  Why Synthesized: ${s.whySynthesized}\n  Investor Alert: ${s.investorAlert}`
        )
        .join('\n\n')
    : '✓ Zero purely synthesized data. All claims are grounded or mathematically calculated.'
}

## MATHEMATICAL FORMULAS (VALIDATED)
${evaluation.ledgerItems
  .filter((i) => i.type === 'MATHEMATICAL_CALCULATION')
  .map((m) => `- ${m.item}: ${m.reportValue} (${m.formulaOrCitation || m.explanation})`)
  .join('\n')}

## DIRECT PITCH DISCLOSURES
${evaluation.ledgerItems
  .filter((i) => i.type === 'DIRECT_PITCH_SOURCE')
  .map((d) => `- ${d.item}: ${d.reportValue} | Quote: ${d.formulaOrCitation || d.sourceValue}`)
  .join('\n')}

Generated by Pitch Black Diligence Director.`;

    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  const filteredItems = evaluation.ledgerItems.filter((item) => {
    if (activeFilter !== 'ALL' && item.type !== activeFilter) return false;
    if (!searchQuery.trim()) return true;
    const q = searchQuery.toLowerCase();
    return (
      item.item.toLowerCase().includes(q) ||
      item.pillar.toLowerCase().includes(q) ||
      item.explanation.toLowerCase().includes(q) ||
      (item.formulaOrCitation && item.formulaOrCitation.toLowerCase().includes(q))
    );
  });

  return (
    <div
      className="fixed inset-0 z-[100] flex items-center justify-center p-3 sm:p-6 bg-zinc-950/70 backdrop-blur-md animate-in fade-in duration-200 overflow-y-auto"
      onClick={onClose}
      role="dialog"
      aria-modal="true"
      aria-labelledby="grounding-modal-title"
    >
      <div
        className="relative w-full max-w-4xl my-auto bg-white border border-zinc-200/90 rounded-3xl shadow-2xl overflow-hidden max-h-[92vh] flex flex-col text-zinc-900"
        onClick={(e) => e.stopPropagation()}
      >
        {/* CRISP HEADER */}
        <div className="flex items-center justify-between p-5 sm:p-6 border-b border-zinc-200 bg-zinc-50/90 shrink-0">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-2xl bg-zinc-900 text-white flex items-center justify-center shadow-xs">
              <ShieldCheck className="w-5 h-5 text-emerald-400" />
            </div>
            <div>
              <div className="flex items-center gap-2 flex-wrap">
                <h2 id="grounding-modal-title" className="text-base sm:text-lg font-bold text-zinc-900 tracking-tight font-serif">
                  Data Grounding &amp; Synthesis Evaluator
                </h2>
                <span className="text-[10px] font-mono font-bold px-2.5 py-0.5 rounded-full bg-zinc-200 text-zinc-800">
                  {companyName}
                </span>
                <span className="text-[10px] font-mono px-2 py-0.5 rounded-full bg-emerald-50 text-emerald-800 border border-emerald-300">
                  {evaluation.evaluationMethod === 'AI_DEEP_EVALUATION' ? '⚡ Gemini Live Verified' : 'Heuristic Grounding Engine'}
                </span>
              </div>
              <p className="text-xs text-zinc-500 mt-0.5">
                Differentiates valid mathematical derivations from information purely synthesized out of nowhere.
              </p>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleCopyReport}
              className="hidden sm:flex items-center gap-1.5 px-3 py-1.5 rounded-xl border border-zinc-200 bg-white hover:bg-zinc-50 text-zinc-700 text-xs font-semibold transition-all shadow-2xs cursor-pointer"
              title="Copy audit summary to clipboard"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5 text-zinc-500" />}
              <span>{copied ? 'Copied' : 'Copy Report'}</span>
            </button>

            <button
              onClick={onClose}
              aria-label="Close Grounding Evaluator"
              className="p-2 rounded-xl text-zinc-400 hover:text-zinc-700 hover:bg-zinc-200/60 transition-colors cursor-pointer"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {/* BODY (SCROLLABLE) */}
        <div className="flex-1 overflow-y-auto p-5 sm:p-6 space-y-6">
          {/* HERO BANNER & SCORECARD */}
          <div className="p-5 sm:p-6 rounded-2xl bg-zinc-900 text-white shadow-md border border-zinc-800 relative overflow-hidden">
            <div className="flex flex-col md:flex-row md:items-center justify-between gap-6 relative z-10">
              <div className="space-y-1.5 max-w-xl">
                <div className="text-[11px] font-mono font-bold tracking-wider uppercase text-emerald-400">
                  Institutional Grounding Score
                </div>
                <h3 className="text-xl sm:text-2xl font-bold font-serif text-white tracking-tight">
                  Overall Grounding Fidelity: {evaluation.grade} Grade
                </h3>
                <p className="text-xs sm:text-sm text-zinc-300 leading-relaxed pt-1">
                  {evaluation.evaluationSummary}
                </p>
              </div>

              {/* Numerical Score Box */}
              <div className="flex items-center gap-3.5 bg-white/10 backdrop-blur-md border border-white/15 px-5 py-3 rounded-2xl shrink-0 self-start md:self-auto shadow-inner">
                <div className="text-right">
                  <div className="text-[10px] font-mono uppercase tracking-wider text-zinc-400 font-bold">
                    Score
                  </div>
                  <div className="text-[11px] font-semibold text-emerald-300">
                    {evaluation.hallucinationRisk.replace(/_/g, ' ')} Risk
                  </div>
                </div>
                <div className="flex items-baseline gap-1">
                  <span className="text-4xl sm:text-5xl font-extrabold tabular-nums tracking-tight text-white font-sans">
                    {evaluation.score.toFixed(1)}
                  </span>
                  <span className="text-sm font-mono text-zinc-400 font-bold">/10</span>
                </div>
              </div>
            </div>

            {/* 3 Crisp Category Counters */}
            <div className="grid grid-cols-1 sm:grid-cols-3 gap-3 mt-5 pt-4 border-t border-zinc-800">
              {/* 1. Directly Grounded */}
              <div className="bg-zinc-800/80 rounded-xl p-3 border border-emerald-500/30 flex items-center justify-between">
                <div>
                  <div className="text-[10px] font-mono uppercase text-zinc-400">Directly Grounded</div>
                  <div className="text-sm font-bold text-emerald-400 mt-0.5">
                    {evaluation.groundedSourceCount} Verified Facts
                  </div>
                </div>
                <CheckCircle2 className="w-5 h-5 text-emerald-400 shrink-0" />
              </div>

              {/* 2. Mathematical Formulas */}
              <div className="bg-zinc-800/80 rounded-xl p-3 border border-blue-500/30 flex items-center justify-between">
                <div>
                  <div className="text-[10px] font-mono uppercase text-zinc-400">Mathematical Formulas</div>
                  <div className="text-sm font-bold text-blue-400 mt-0.5">
                    {evaluation.mathematicalDerivationsCount} Valid Calculations
                  </div>
                </div>
                <Calculator className="w-5 h-5 text-blue-400 shrink-0" />
              </div>

              {/* 3. Purely Synthesized Alert */}
              <div
                className={`rounded-xl p-3 border flex items-center justify-between ${
                  evaluation.purelySynthesizedCount > 0
                    ? 'bg-rose-950/40 border-rose-500/50 text-rose-300'
                    : 'bg-zinc-800/80 border-zinc-700 text-zinc-400'
                }`}
              >
                <div>
                  <div className="text-[10px] font-mono uppercase">Purely Synthesized</div>
                  <div
                    className={`text-sm font-bold mt-0.5 ${
                      evaluation.purelySynthesizedCount > 0 ? 'text-rose-400' : 'text-zinc-200'
                    }`}
                  >
                    {evaluation.purelySynthesizedCount} Made-Up Items
                  </div>
                </div>
                <AlertTriangle
                  className={`w-5 h-5 shrink-0 ${
                    evaluation.purelySynthesizedCount > 0 ? 'text-rose-400 animate-pulse' : 'text-zinc-500'
                  }`}
                />
              </div>
            </div>
          </div>

          {/* CRITICAL ATTENTION SECTION: PURELY SYNTHESIZED OUT OF NOWHERE */}
          {evaluation.purelySynthesizedCount > 0 ? (
            <div className="p-4 sm:p-5 rounded-2xl bg-rose-50/90 border border-rose-200 shadow-2xs space-y-3">
              <div className="flex items-start justify-between gap-3">
                <div className="flex items-center gap-2">
                  <div className="w-7 h-7 rounded-lg bg-rose-600 text-white flex items-center justify-center shrink-0">
                    <AlertTriangle className="w-4 h-4" />
                  </div>
                  <div>
                    <h4 className="text-xs sm:text-sm font-bold text-rose-950 uppercase tracking-wide">
                      Purely Synthesized Data (User Attention Required)
                    </h4>
                    <p className="text-xs text-rose-800 mt-0.5 leading-relaxed">
                      The following information was <strong>not in the uploaded pitch and cannot be calculated from a mathematical formula</strong>. The LLM generated this out of nowhere for explanation:
                    </p>
                  </div>
                </div>
                <span className="text-[10px] font-mono font-bold px-2 py-0.5 rounded-full bg-rose-200 text-rose-900 border border-rose-300 shrink-0">
                  {evaluation.purelySynthesizedCount} Flags
                </span>
              </div>

              <div className="grid gap-2.5 pt-1">
                {evaluation.purelySynthesizedItems.map((item) => (
                  <div key={item.id} className="p-3.5 rounded-xl bg-white border border-rose-200 shadow-2xs text-xs space-y-1.5">
                    <div className="flex items-center justify-between gap-2 flex-wrap">
                      <div className="flex items-center gap-2">
                        <span className="text-[9px] font-mono font-extrabold px-1.5 py-0.5 rounded bg-rose-600 text-white uppercase">
                          {item.severity}
                        </span>
                        <strong className="text-zinc-900 font-bold">{item.item}</strong>
                        <span className="text-[10px] font-mono text-zinc-500">[{item.pillar}]</span>
                      </div>
                      <span className="text-[10px] font-mono font-bold text-rose-700 bg-rose-50 px-2 py-0.5 rounded-full border border-rose-200">
                        Synthesized (Not in Pitch &amp; Not a Formula)
                      </span>
                    </div>

                    <div className="p-2 rounded-lg bg-zinc-50 border border-zinc-200 text-zinc-700 font-medium">
                      <span className="text-zinc-400 font-mono text-[10px] mr-1">Report Claim:</span>
                      <span>"{item.claimInReport}"</span>
                    </div>

                    <div className="flex items-start gap-1.5 text-zinc-600 pt-0.5 leading-relaxed">
                      <span className="font-bold text-rose-900 shrink-0">Investor Alert:</span>
                      <span>{item.investorAlert}</span>
                    </div>
                  </div>
                ))}
              </div>
            </div>
          ) : (
            <div className="p-3.5 rounded-2xl bg-emerald-50 border border-emerald-200 flex items-center gap-2.5 text-xs text-emerald-900 font-medium">
              <CheckCircle2 className="w-4 h-4 text-emerald-600 shrink-0" />
              <span>
                <strong>Clean Verification:</strong> Zero purely synthesized data detected. All reported figures and claims are either directly backed by uploaded pitch disclosures or standard mathematical formulas.
              </span>
            </div>
          )}

          {/* FILTER TOOLBAR & LIVE SCAN BUTTON */}
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 border-b border-zinc-200 pb-3">
            {/* Filter Chips */}
            <div className="flex items-center gap-1.5 overflow-x-auto no-scrollbar">
              <button
                onClick={() => setActiveFilter('ALL')}
                className={`px-3 py-1.5 rounded-xl text-xs font-bold transition-all cursor-pointer ${
                  activeFilter === 'ALL'
                    ? 'bg-zinc-900 text-white shadow-xs'
                    : 'bg-zinc-100 text-zinc-600 hover:bg-zinc-200'
                }`}
              >
                All Items ({evaluation.ledgerItems.length})
              </button>

              {evaluation.purelySynthesizedCount > 0 && (
                <button
                  onClick={() => setActiveFilter('PURE_SYNTHESIS_ALERT')}
                  className={`px-3 py-1.5 rounded-xl text-xs font-bold transition-all cursor-pointer flex items-center gap-1 ${
                    activeFilter === 'PURE_SYNTHESIS_ALERT'
                      ? 'bg-rose-600 text-white shadow-xs'
                      : 'bg-rose-50 text-rose-800 border border-rose-200 hover:bg-rose-100'
                  }`}
                >
                  <AlertTriangle className="w-3 h-3" />
                  <span>Purely Synthesized ({evaluation.purelySynthesizedCount})</span>
                </button>
              )}

              <button
                onClick={() => setActiveFilter('MATHEMATICAL_CALCULATION')}
                className={`px-3 py-1.5 rounded-xl text-xs font-bold transition-all cursor-pointer flex items-center gap-1 ${
                  activeFilter === 'MATHEMATICAL_CALCULATION'
                    ? 'bg-blue-600 text-white shadow-xs'
                    : 'bg-blue-50 text-blue-800 border border-blue-200 hover:bg-blue-100'
                }`}
              >
                <Calculator className="w-3 h-3" />
                <span>Formulas (Valid) ({evaluation.mathematicalDerivationsCount})</span>
              </button>

              <button
                onClick={() => setActiveFilter('DIRECT_PITCH_SOURCE')}
                className={`px-3 py-1.5 rounded-xl text-xs font-bold transition-all cursor-pointer flex items-center gap-1 ${
                  activeFilter === 'DIRECT_PITCH_SOURCE'
                    ? 'bg-emerald-600 text-white shadow-xs'
                    : 'bg-emerald-50 text-emerald-800 border border-emerald-200 hover:bg-emerald-100'
                }`}
              >
                <CheckCircle2 className="w-3 h-3" />
                <span>Pitch Quotes ({evaluation.groundedSourceCount})</span>
              </button>
            </div>

            {/* Search and Re-run */}
            <div className="flex items-center gap-2 shrink-0">
              <div className="relative">
                <Search className="w-3.5 h-3.5 text-zinc-400 absolute left-2.5 top-1/2 -translate-y-1/2" />
                <input
                  type="text"
                  placeholder="Filter items..."
                  value={searchQuery}
                  onChange={(e) => setSearchQuery(e.target.value)}
                  className="pl-8 pr-2.5 py-1.5 bg-zinc-50 border border-zinc-200 rounded-xl text-xs focus:outline-none focus:border-zinc-400 w-36 sm:w-44"
                />
              </div>

              <button
                onClick={handleRunLiveAIVerification}
                disabled={isLiveVerifying}
                className="flex items-center gap-1 px-3 py-1.5 rounded-xl text-xs font-bold bg-white hover:bg-zinc-50 text-zinc-800 border border-zinc-200 shadow-2xs transition-all cursor-pointer disabled:opacity-50"
                title="Re-run deep verification with Gemini"
              >
                <RefreshCw className={`w-3.5 h-3.5 text-zinc-500 ${isLiveVerifying ? 'animate-spin' : ''}`} />
                <span className="hidden sm:inline">{isLiveVerifying ? 'Scanning...' : 'Live AI Scan'}</span>
              </button>
            </div>
          </div>

          {/* CRISP DATA FAITHFULNESS LEDGER TABLE */}
          <div className="space-y-3">
            <div className="text-[11px] font-mono text-zinc-500 flex items-center justify-between">
              <span>Showing {filteredItems.length} audited diligence items:</span>
              <span>Classified by verification type</span>
            </div>

            <div className="border border-zinc-200/90 rounded-2xl overflow-hidden shadow-2xs divide-y divide-zinc-200">
              {filteredItems.map((item) => {
                const isPureSynthesis = item.type === 'PURE_SYNTHESIS_ALERT';
                const isMath = item.type === 'MATHEMATICAL_CALCULATION';
                const isDirect = item.type === 'DIRECT_PITCH_SOURCE';

                return (
                  <div
                    key={item.id}
                    className={`p-4 transition-colors space-y-2 ${
                      isPureSynthesis
                        ? 'bg-rose-50/40 hover:bg-rose-50/70'
                        : isMath
                        ? 'bg-blue-50/20 hover:bg-blue-50/40'
                        : 'bg-white hover:bg-zinc-50/80'
                    }`}
                  >
                    <div className="flex items-center justify-between gap-3 flex-wrap">
                      <div className="flex items-center gap-2">
                        <span className="text-xs font-bold text-zinc-900">{item.item}</span>
                        <span className="text-[10px] font-mono text-zinc-500 bg-zinc-100 px-2 py-0.5 rounded-md">
                          {item.pillar}
                        </span>
                      </div>

                      {/* Crisp Badge */}
                      {isDirect && (
                        <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-[10px] font-mono font-bold bg-emerald-100 text-emerald-800 border border-emerald-300">
                          <CheckCircle2 className="w-3 h-3 text-emerald-600" />
                          VERIFIED IN PITCH
                        </span>
                      )}
                      {isMath && (
                        <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-[10px] font-mono font-bold bg-blue-100 text-blue-800 border border-blue-300">
                          <Calculator className="w-3 h-3 text-blue-600" />
                          MATHEMATICAL FORMULA (VALID)
                        </span>
                      )}
                      {isPureSynthesis && (
                        <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-[10px] font-mono font-bold bg-rose-100 text-rose-800 border border-rose-300 animate-pulse">
                          <AlertTriangle className="w-3 h-3 text-rose-600" />
                          PURELY SYNTHESIZED (ALERT)
                        </span>
                      )}
                    </div>

                    {/* Side-by-side values */}
                    <div className="grid grid-cols-1 sm:grid-cols-2 gap-2 text-xs">
                      <div className="p-2.5 rounded-xl bg-white border border-zinc-200/80">
                        <div className="text-[10px] font-mono text-zinc-500 uppercase">Pitch Ingest Data:</div>
                        <div className="font-semibold text-zinc-800 mt-0.5">{item.sourceValue}</div>
                      </div>
                      <div className="p-2.5 rounded-xl bg-white border border-zinc-200/80">
                        <div className="text-[10px] font-mono text-zinc-500 uppercase">Report Diligence Figure:</div>
                        <div className="font-bold text-zinc-900 mt-0.5">{item.reportValue}</div>
                      </div>
                    </div>

                    {/* Formula or Citation Box */}
                    {item.formulaOrCitation && (
                      <div
                        className={`p-2 rounded-xl text-[11px] font-mono ${
                          isMath
                            ? 'bg-blue-50 text-blue-900 border border-blue-200'
                            : isDirect
                            ? 'bg-emerald-50 text-emerald-900 border border-emerald-200 italic'
                            : 'bg-zinc-100 text-zinc-700'
                        }`}
                      >
                        <span className="font-bold mr-1">
                          {isMath ? 'Mathematical Formula:' : 'Source Citation:'}
                        </span>
                        <span>{item.formulaOrCitation}</span>
                      </div>
                    )}

                    <p className="text-xs text-zinc-600 leading-relaxed pt-0.5">
                      {item.explanation}
                    </p>
                  </div>
                );
              })}
            </div>
          </div>

          {/* COLLAPSIBLE RAW PITCH TEXT DRAWER */}
          <div className="border border-zinc-200 rounded-2xl overflow-hidden bg-zinc-50">
            <button
              type="button"
              onClick={() => setShowRawPitch(!showRawPitch)}
              className="w-full flex items-center justify-between p-4 text-xs font-bold text-zinc-800 hover:bg-zinc-100/80 transition-colors cursor-pointer"
            >
              <div className="flex items-center gap-2">
                <FileText className="w-4 h-4 text-zinc-500" />
                <span>View Raw Uploaded Pitch Text ({evaluation.sourceWordCount} words)</span>
              </div>
              <span className="text-[11px] text-zinc-500 font-normal">
                {showRawPitch ? 'Hide Pitch Data ▲' : 'Show Pitch Data ▼'}
              </span>
            </button>

            {showRawPitch && (
              <div className="p-4 border-t border-zinc-200 bg-zinc-900 text-zinc-200 font-mono text-xs whitespace-pre-wrap leading-relaxed max-h-72 overflow-y-auto">
                {rawPitchText || 'No raw pitch text currently stored for this deal.'}
              </div>
            )}
          </div>
        </div>

        {/* MODAL FOOTER */}
        <div className="flex items-center justify-between p-4 sm:p-5 border-t border-zinc-200 bg-zinc-50/90 shrink-0">
          <div className="flex items-center gap-2 text-xs text-zinc-500">
            <Info className="w-4 h-4 text-zinc-400 shrink-0" />
            <span className="hidden sm:inline">
              Formulas are marked valid. Only data synthesized out of nowhere is highlighted for verification.
            </span>
            <span className="inline sm:hidden font-mono text-[11px]">Score: {evaluation.score}/10</span>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleCopyReport}
              className="flex sm:hidden items-center gap-1.5 px-3 py-2 rounded-xl border border-zinc-200 bg-white text-zinc-700 text-xs font-semibold"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5 text-zinc-500" />}
              <span>{copied ? 'Copied' : 'Copy'}</span>
            </button>
            <button
              onClick={onClose}
              className="px-5 py-2.5 rounded-xl bg-zinc-900 hover:bg-black text-white text-xs font-bold transition-all shadow-md cursor-pointer"
            >
              Done / Return to Deal Room
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
